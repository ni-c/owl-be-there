/**
 * Golden QR matrices, produced once by libqrencode 4.1.1 and kept.
 *
 * The command, for anyone reproducing them:
 *
 *     qrencode -l M -8 -m 0 -t ASCII -o - <text>
 *
 * — level M, byte mode forced, no quiet zone. Its two-character-per-module
 * ASCII output was folded to one character per module: `#` dark, `.` light.
 *
 * **Why an outside implementation rather than our own output.** A fixture taken
 * from the thing it tests only says that nothing changed; it cannot say that
 * anything was ever right. Agreeing with a C library that has been read by a
 * great many cameras means the mode, the version choice, the Reed–Solomon
 * coding, the block interleaving, the module layout, the format bits and the
 * mask all match.
 *
 * **Why these four payloads.** They are cases where the two implementations
 * agree completely, and that is worth saying out loud: on many inputs they
 * choose a *different mask*, and the matrices then differ everywhere. That is
 * not a bug in either — mask selection is a quality heuristic over a rule the
 * standard leaves famously under-specified. It was checked rather than assumed:
 * the event links where the masks differ were rendered from this encoder and
 * read back correctly by zbar.
 *
 * The four cover the ground that matters: one small symbol, two links shaped
 * like the ones the application encodes, and one large enough to be split into
 * several blocks and interleaved.
 */
